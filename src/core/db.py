import os
import re
import sqlite3
import threading
from datetime import datetime
from pathlib import Path
from typing import List, Optional

from src.config import DATA_DIR

# ---------------- DSN / 驱动切换点（信创预留） ----------------
# 优先级：TELEOPS_DB_FILE（测试隔离用的单文件 SQLite）> TELEOPS_DB_DSN（信创/PG 切换点）>
#         默认 data/teleops.db。
# 信创/PG 形如：
#   dm://user:pass@host:5236/dbname
#   kingbase://user:pass@host:54321/dbname
#   postgresql://user:pass@host:5432/dbname
# 切换时只需改 TELEOPS_DB_DSN + 在部署环境 pip install 对应驱动。
_DB_FILE = os.environ.get("TELEOPS_DB_FILE")
if _DB_FILE:
    DB_DSN = "sqlite://" + _DB_FILE
else:
    DB_DSN = os.environ.get("TELEOPS_DB_DSN") or f"sqlite://{DATA_DIR / 'teleops.db'}"

# 非 SQLite 协议 → 需要的 Python 驱动模块（懒加载，装了才连）
_DRIVER_MODULES = {
    "dm": "dmPython",
    "kingbase": "kingbase",
    "postgresql": "psycopg",
    "postgres": "psycopg",
}
# 这些协议使用 %s 占位符（SQLite/达梦/金仓用 ?）
_PCTS_PLACEHOLDER_SCHEMES = {"postgresql", "postgres", "dm", "kingbase"}


def _parse_dsn():
    if "://" not in DB_DSN:
        return "sqlite", DB_DSN  # 裸路径视为 sqlite 文件
    scheme, rest = DB_DSN.split("://", 1)
    return scheme.lower(), rest


def _ph(sql: str) -> str:
    """占位符方言归一：PG/达梦/金仓用 %s，其余（含 SQLite）保持 ?。"""
    scheme, _ = _parse_dsn()
    if scheme in _PCTS_PLACEHOLDER_SCHEMES:
        return sql.replace("?", "%s")
    return sql


# ---------------- SQLite -> PG/信创 方言翻译（DDL / 写语句） ----------------
# 非 SQLite 协议（PG/达梦/金仓）的少数 SQLite 专属语法需要翻译，避免直连时报语法错。
# 仅当 DSN 为非 SQLite 协议时调用，SQLite 路径完全不受影响。
_PK_COLS = {
    # 表 -> 主键列（用于把 SQLite 的 INSERT OR IGNORE 翻成 ON CONFLICT DO NOTHING）
    "workspaces": ["id"], "agents": ["id"], "requirements": ["id"],
    "tools": ["name"], "messages": ["id"],
    "role_permissions": ["role_id", "permission"], "user_roles": ["user_id", "role_id"],
    "users": ["id"], "audit_log": ["id"],
}


def _translate_sqlite_to_pg(sql: str) -> str:
    """把 SQLite 专属 DDL / 写语句翻译为 PG/信创兼容写法。

    - ``INTEGER PRIMARY KEY AUTOINCREMENT`` / ``INTEGER PRIMARY KEY`` -> 自增主键
      （PG 用 GENERATED BY DEFAULT AS IDENTITY；达梦/金仓语法接近，统一按 PG 形态）。
    - ``INSERT OR IGNORE INTO <tbl> ...`` -> ``INSERT INTO <tbl> ... ON CONFLICT (<pk>) DO NOTHING``。
    """
    s = sql
    s = re.sub(r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT",
               "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", s, flags=re.I)
    s = re.sub(r"INTEGER\s+PRIMARY\s+KEY\b",
               "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", s, flags=re.I)
    m = re.search(r"INSERT\s+OR\s+IGNORE\s+INTO\s+([A-Za-z_]+)", s, flags=re.I)
    if m:
        tbl = m.group(1)
        pk = _PK_COLS.get(tbl)
        s = re.sub(r"INSERT\s+OR\s+IGNORE\s+INTO", "INSERT INTO", s, flags=re.I)
        if pk:
            s = s.rstrip(";") + f" ON CONFLICT ({', '.join(pk)}) DO NOTHING"
    return s


def _pg_sql(sql: str) -> str:
    """按协议返回最终要执行的 SQL：非 SQLite 协议先翻方言再归一占位符；SQLite 原样。"""
    scheme, _ = _parse_dsn()
    if scheme in _PCTS_PLACEHOLDER_SCHEMES:
        return _translate_sqlite_to_pg(_ph(sql))
    return sql


