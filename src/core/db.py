def _now() -> str:
    return datetime.now().isoformat(timespec="seconds")


def _raw_connect():
    """按 DSN 选择驱动并建立连接（缓存于模块级 _conn）。"""
    global _conn
    scheme, target = _parse_dsn()
    if scheme == "sqlite":
        _conn = sqlite3.connect(target, check_same_thread=False, timeout=5.0)
        _conn.row_factory = sqlite3.Row
        _conn.execute("PRAGMA foreign_keys = ON")
        _conn.execute("PRAGMA journal_mode = WAL")
        _conn.execute("PRAGMA synchronous = NORMAL")
        _conn.execute("PRAGMA busy_timeout = 5000")
        return _conn
    # ---- 信创 / PostgreSQL 切换点 ----
    mod = _DRIVER_MODULES.get(scheme)
    if not mod:
        raise RuntimeError(
            f"不支持的数据库协议 '{scheme}'（DSN={DB_DSN}）。"
            f"当前支持的协议：sqlite / dm / kingbase / postgresql。")
    try:
        driver = importlib.import_module(mod)
    except ImportError as e:
        raise RuntimeError(
            f"未安装 '{scheme}' 数据库驱动（需模块 {mod}），无法连接 {DB_DSN}。\n"
            f"请在部署环境执行：pip install {mod}\n"
            f"（当前开发/演示默认使用 SQLite，设置 TELEOPS_DB_DSN=sqlite://<路径> 即可）"
        ) from e
    # 达梦/金仓/PG 的 connect 接口基本一致（传 DSN 字符串）
    _conn = driver.connect(target)
    # PG（psycopg）结果行设为 dict，统一走 _row_to_dict；其余驱动保持默认
    if driver.__name__ == "psycopg":
        try:
            import psycopg
            _conn.row_factory = psycopg.rows.dict_row
        except Exception:
            pass
    return _conn


def get_conn() -> object:
    """惰性创建并缓存全局连接（线程安全）。首次连接建表 + 迁移 + 播种 RBAC。"""
    global _conn
    if _conn is None:
        _raw_connect()
        _init_schema()
        _migrate_columns()
        _migrate_from_json()
        _seed_rbac()
    return _conn


def _init_schema():
    scheme, _ = _parse_dsn()
    if scheme == "sqlite":
        get_conn().executescript(_SCHEMA)
        get_conn().commit()
        return
    # PG/达梦/金仓：executescript 不可用，按 ; 拆成单条 DDL 并翻方言后逐条执行
    conn = get_conn()
    for stmt in _SCHEMA.split(";"):
        sql = _pg_sql(stmt.strip())
        if not sql:
            continue
        conn.execute(sql)
    conn.commit()


def _migrate_columns():
    """为既有库补齐新列（org_id），幂等。"""
    for col, table in (("org_id", "users"), ("org_id", "workspaces")):
        try:
            get_conn().execute(f"ALTER TABLE {table} ADD COLUMN {col} TEXT")
            get_conn().commit()
        except Exception:
            pass  # 列已存在则忽略


def _migrate_from_json():
    """仅在 workspaces 表为空且遗留 JSON 存在时迁移一次。"""
    if get_conn().execute("SELECT COUNT(*) FROM workspaces").fetchone()[0] > 0:
        return
    # 业务域 + Agent
    wf = DATA_DIR / "workspaces.json"
    if wf.exists():
        try:
            data = json.loads(wf.read_text(encoding="utf-8"))
        except Exception:
            data = {}
        for w in data.get("workspaces", []):
            get_conn().execute(
                "INSERT OR IGNORE INTO workspaces (id,name,adapter_id,mode,owner_id,created_at) "
                "VALUES (?,?,?,?,?,?)",
                (w["id"], w["name"], w.get("adapter_id"), w.get("mode", "auto"),
                 None, _now()))
            for a in w.get("agents", []):
                get_conn().execute(
                    "INSERT OR IGNORE INTO agents "
                    "(id,workspace_id,name,kind,scope,description,is_primary,status) "
                    "VALUES (?,?,?,?,?,?,?,?)",
                    (a["id"], w["id"], a["name"], a["kind"],
                     json.dumps(a.get("scope", []), ensure_ascii=False),
                     a.get("description", ""), 1 if a.get("primary") else 0,
                     a.get("status", "idle")))
    # 需求
    rf = DATA_DIR / "requirements.json"
    if rf.exists():
        try:
            data = json.loads(rf.read_text(encoding="utf-8"))
        except Exception:
            data = {}
        for r in data.get("requirements", []):
            get_conn().execute(
                "INSERT OR IGNORE INTO requirements "
                "(id,workspace_id,status,data,created_at,updated_at) VALUES (?,?,?,?,?,?)",
                (r.get("id"), r.get("workspace_id"), r.get("status", "pending"),
                 json.dumps(r, ensure_ascii=False), r.get("created_at"), r.get("updated_at")))
    # 工具
    tf = DATA_DIR / "tools.json"
    if tf.exists():
        try:
            data = json.loads(tf.read_text(encoding="utf-8"))
        except Exception:
            data = {}
        for t in data.get("tools", []):
            get_conn().execute(
                "INSERT OR IGNORE INTO tools "
                "(name,executor,risk,require_human_approval,description,workspace_id,created_at) "
                "VALUES (?,?,?,?,?,?,?)",
                (t.get("name"), t.get("executor"), t.get("risk", "low"),
                 1 if t.get("require_human_approval") else 0,
                 t.get("description", ""), t.get("workspace_id"), _now()))
    # 操作记录
    mf = DATA_DIR / "messages.json"
    if mf.exists():
        try:
            data = json.loads(mf.read_text(encoding="utf-8"))
        except Exception:
            data = {}
        for ws_id, msgs in data.get("messages", {}).items():
            for m in msgs:
                get_conn().execute(
                    "INSERT OR IGNORE INTO messages "
                    "(id,workspace_id,agent_id,agent_name,kind,summary,detail,ts) VALUES (?,?,?,?,?,?,?,?)",
                    (m.get("id"), ws_id, m.get("agent_id"), m.get("agent_name"),
                     m.get("kind"), m.get("summary"), m.get("detail"), m.get("ts")))
    get_conn().commit()


# ---------------- RBAC 播种（幂等） ----------------
def _seed_rbac():
    """播根组织 + 内置角色 + 为既有用户指派组织/角色（向后兼容）。

    - 根组织 grp-root（集团总部）。
    - 5 个内置角色及其权限。
    - 既有 users.org_id 为空 → 归入根组织；is_admin 者授 super_admin，否则授 sre。
    - 新用户由 auth.create_user 自行建个人组织叶节点并授角色。
    """
    if not query_one("SELECT 1 FROM org_units WHERE id=?", (ROOT_ORG_ID,)):
        execute("INSERT INTO org_units (id,name,parent_id,path,level,org_type) "
                "VALUES (?,?,?,?,?,?)",
                (ROOT_ORG_ID, "集团总部", None, "/" + ROOT_ORG_ID, 0, "group"))
    for rid, perms in BUILTIN_ROLES.items():
        if not query_one("SELECT 1 FROM roles WHERE id=?", (rid,)):
            execute("INSERT INTO roles (id,name,builtin) VALUES (?,?,1)", (rid, rid))
        for p in perms:
            execute("INSERT OR IGNORE INTO role_permissions (role_id,permission) VALUES (?,?)",
                    (rid, p))
    # 既有用户补齐组织 + 角色
    for u in query("SELECT * FROM users"):
        if not u["org_id"]:
            execute("UPDATE users SET org_id=? WHERE id=?", (ROOT_ORG_ID, u["id"]))
        rid = "super_admin" if u["is_admin"] else "sre"
        execute("INSERT OR IGNORE INTO user_roles (user_id,role_id) VALUES (?,?)",
                (u["id"], rid))


def org_path_of(org_id: str) -> Optional[str]:
    """返回组织物化路径（用于子树包含判定）；不存在返回 None。"""
    r = query_one("SELECT path FROM org_units WHERE id=?", (org_id,))
    return r["path"] if r else None


# ---------------- 通用封装（线程安全 + 方言中立） ----------------
def execute(sql: str, params=()):
    """执行写操作并提交，返回 cursor（调用方可用 rowcount 判断影响行数）。

    注意：``get_conn()`` 必须在加锁**之前**调用。首次调用会触发建表/迁移/播种，
    而播种内部又会回调用 ``execute/query``——若 get_conn 在锁内，会因非重入锁
    造成递归死锁。把初始化放在锁外即可解开。
    """
    conn = get_conn()
    with _LOCK:
        cur = conn.execute(_pg_sql(sql), params)
        conn.commit()
    return cur


def query(sql: str, params=()):
    conn = get_conn()
    with _LOCK:
        rows = conn.execute(_pg_sql(sql), params).fetchall()
    # PG 驱动返回的不是 sqlite.Row，统一转 dict 方便上层访问
    return [_row_to_dict(r) for r in rows]


def query_one(sql: str, params=()):
    conn = get_conn()
    with _LOCK:
        row = conn.execute(_pg_sql(sql), params).fetchone()
    return _row_to_dict(row) if row is not None else None


def _row_to_dict(row):
    if isinstance(row, dict):
        return row
    try:
        return {k: row[k] for k in row.keys()}
    except Exception:
        return dict(row)


# ---------------- 操作审计（多租户问责） ----------------
def audit(actor, action, workspace_id=None, detail=None, result="ok",
          actor_id=None, ip=None):
    """写入一条操作审计记录。任何异常都静默吞掉，绝不阻断主流程。

    actor：操作人（用户名 / 'anonymous' / 'system'）
    action：动作标识（如 auth.login / workspace.create / agent.delete / stream.start /
            tool.build 等）
    workspace_id：受影响的业务域（可空，如登录类动作）
    detail：人类可读摘要，或结构化 dict（自动 JSON 化）
    result：'ok' / 'denied' / 'error'
    actor_id / ip：可选，便于回溯具体账号与来源
    """
    try:
        if detail is not None and not isinstance(detail, str):
            detail = json.dumps(detail, ensure_ascii=False)
        conn = get_conn()
        with _LOCK:
            conn.execute(
                "INSERT INTO audit_log "
                "(ts,actor,actor_id,action,workspace_id,detail,result,ip) "
                "VALUES (?,?,?,?,?,?,?,?)",
                (_now(), str(actor), actor_id, action, workspace_id, detail,
                 result, ip))
            conn.commit()
    except Exception as e:  # 审计失败绝不影响主业务
        print(f"[warn] audit log write failed: {e}")


def audit_rows(limit=50, offset=0, workspace_id=None, actor_id=None):
    """按条件倒序读取审计记录（最新在前）。供 GET /audit 使用。"""
    clauses, params = [], []
    if workspace_id is not None:
        clauses.append("workspace_id=?")
        params.append(workspace_id)
    if actor_id is not None:
        clauses.append("actor_id=?")
        params.append(actor_id)
    where = ("WHERE " + " AND ".join(clauses)) if clauses else ""
    rows = query(
        f"SELECT * FROM audit_log {where} ORDER BY id DESC LIMIT ? OFFSET ?",
        tuple(params) + (limit, offset))
    total = query_one(
        f"SELECT COUNT(*) AS c FROM audit_log {where}", tuple(params))["c"]
    return rows, total
